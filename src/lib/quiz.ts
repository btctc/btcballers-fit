// The two sides of the ball. Spacing and movement counts as offense.
// The quiz mixes both, then shows how the player did on each side after a run.
export type Side = "offense" | "defense";
export const sideOf = (x: Term): Side => (x.pillar === "defense" ? "defense" : "offense");
export const sideNames: Record<Side, string> = { offense: "Offense", defense: "Defense" };
